#!/usr/bin/env node
/**
 * Build the plugin halves into the exact shapes DSH loads.
 *
 * DSH does NOT compile plugin sources; it consumes prebuilt artifacts:
 *   - host half: a plain ESM module at lib/index.js (Node imports it directly)
 *   - browser half: a bundle that calls window.__ModuleLoader__.load({ id, factory })
 *
 * This script performs the small, dependency-free transformation the browser
 * half needs. It deliberately does not use a bundler: the client half imports
 * nothing, so wrapping the module body in a factory is the whole job. That
 * keeps the plugin buildable with nothing but Node.
 */

import { mkdir, readFile, writeFile, cp } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(await readFile(join(here, 'package.json'), 'utf8'))
const packageId = pkg.name

const outDir = join(here, 'lib')
await mkdir(outDir, { recursive: true })

// ---- host half: copy verbatim (pure ESM, imported by Node) ----
const hostSource = await readFile(join(here, 'src/index.js'), 'utf8')
await writeFile(join(outDir, 'index.js'), hostSource, 'utf8')

// ---- browser half: wrap in the loader factory ----
const clientSource = await readFile(join(here, 'src/client.js'), 'utf8')

// The factory body is the module source with `export` keywords stripped and
// ESM `import` statements rewritten to loader `require` calls: the loader
// expects a CommonJS-shaped module whose exports are assigned onto
// `module.exports`. Only the import/export forms this plugin actually uses are
// rewritten, so the transformation stays predictable.
const importNames = []
const factoryBody = clientSource
  // `import { a, b as c } from 'mod'` -> `const { a, b: c } = require('mod')`
  .replace(/^import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm, (_m, names, mod) => {
    const local = `__mod${importNames.length}`
    importNames.push({ local, mod })
    // Translate ESM rename syntax (`x as y`) to destructuring rename (`x: y`).
    const bindings = names
      .split(',')
      .map((entry) => entry.trim())
      .filter(Boolean)
      .map((entry) => entry.replace(/\s+as\s+/, ': '))
      .join(', ')
    return `const ${local} = require(${JSON.stringify(mod)}); const { ${bindings} } = ${local};`
  })
  // `import X from 'mod'` -> `const X = require('mod')`
  .replace(/^import\s+(\w+)\s+from\s*['"]([^'"]+)['"];?\s*$/gm, (_m, name, mod) => {
    importNames.push({ local: name, mod })
    return `const ${name} = require(${JSON.stringify(mod)});`
  })
  .replace(/^export\s+const\s+(\w+)\s*=/gm, 'const $1 =')
  .replace(/^export\s+function\s+(\w+)/gm, 'function $1')
  .replace(/^export\s+default\s+/gm, 'const __default = ')
  .replace(/^export\s+\{[^}]*\}\s*;?\s*$/gm, '')

// Re-export the two names the loader contract requires.
const needsInject = /const\s+inject\s*=/.test(factoryBody)
const needsApply = /function\s+apply\s*\(/.test(factoryBody)
if (!needsApply) throw new Error('build: client half must define apply()')

// Declare every external module request so the composer can resolve them
// against the frozen platform table instead of failing on an unknown request.
const externalList = [...new Set(importNames.map(({ mod }) => mod))]

const clientBundle = `// Generated by build.mjs — do not edit. Source: src/client.js
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(packageId)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${factoryBody
  .split('\n')
  .map((line) => (line.length > 0 ? `\t\t${line}` : line))
  .join('\n')}
${needsInject ? '\t\texports.inject = inject;\n' : ''}\t\texports.apply = apply;
\t\treturn module.exports;
\t}
});
`

await writeFile(join(outDir, 'client.js'), clientBundle, 'utf8')

console.log(`built ${packageId}:\n  lib/index.js\n  lib/client.js`)
